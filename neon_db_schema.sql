-- 1. Enable Core & Vector Extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgvector";

-- 2. Define Enum Types for Categories & Technical Depth Ratings
DO $$ BEGIN
    CREATE TYPE source_category AS ENUM (
        'casestudies', 
        'security', 
        'compliance', 
        'infra', 
        'models', 
        'industry'
    );
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
    CREATE TYPE depth_level_enum AS ENUM (
        'L1 OVERVIEW', 
        'L2 DEEP DIVE', 
        'L3 MATH/KERNEL'
    );
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

-- 3. Core Articles Table
CREATE TABLE IF NOT EXISTS articles (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    title TEXT NOT NULL,
    source_name VARCHAR(100) NOT NULL,
    source_url TEXT UNIQUE NOT NULL,
    category source_category NOT NULL DEFAULT 'models',
    depth_level depth_level_enum NOT NULL DEFAULT 'L2 DEEP DIVE',
    
    -- Structured Content Generated by Gemini Ingestion Pipeline
    tldr TEXT NOT NULL,
    takeaways JSONB NOT NULL DEFAULT '[]'::jsonb,
    code_snippet TEXT,                            -- Python/CUDA kernel snippet
    full_analysis TEXT,                           -- Detailed breakdown for detail modal
    
    -- Repository & Benchmark Metadata
    github_repo_name VARCHAR(255),
    github_repo_url TEXT,
    github_stars VARCHAR(20),
    metric_label VARCHAR(100),                    -- e.g., "MMLU Score"
    metric_value VARCHAR(50),                     -- e.g., "88.5%"
    
    -- Timestamps
    published_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Vector Embeddings Table
-- Optimized for 384-dimensional BGE embeddings to minimize memory footprint in Neon
CREATE TABLE IF NOT EXISTS article_embeddings (
    article_id UUID PRIMARY KEY REFERENCES articles(id) ON DELETE CASCADE,
    embedding vector(384) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Performance Indexes for Filtered Queries
CREATE INDEX IF NOT EXISTS idx_articles_category ON articles(category);
CREATE INDEX IF NOT EXISTS idx_articles_published ON articles(published_at DESC);
CREATE INDEX IF NOT EXISTS idx_articles_depth ON articles(depth_level);

-- HNSW Vector Index optimized for fast approximate nearest neighbor search (Cosine Distance)
CREATE INDEX IF NOT EXISTS idx_article_embeddings_hnsw 
ON article_embeddings 
USING hnsw (embedding vector_cosine_ops) 
WITH (m = 16, ef_construction = 64);

-- 6. Neon-Optimized Hybrid Vector Search Function (RPC)
CREATE OR REPLACE FUNCTION search_articles(
    query_embedding vector(384),
    filter_category source_category DEFAULT NULL,
    match_threshold FLOAT DEFAULT 0.5,
    match_count INT DEFAULT 20
)
RETURNS TABLE (
    id UUID,
    title TEXT,
    source_name VARCHAR(100),
    source_url TEXT,
    category source_category,
    depth_level depth_level_enum,
    tldr TEXT,
    takeaways JSONB,
    code_snippet TEXT,
    github_repo_name VARCHAR(255),
    github_stars VARCHAR(20),
    metric_label VARCHAR(100),
    metric_value VARCHAR(50),
    published_at TIMESTAMPTZ,
    similarity FLOAT
)
LANGUAGE plpgsql
AS $$
BEGIN
    -- Configure HNSW search recall quality per-session for Neon compute optimization
    SET LOCAL hnsw.ef_search = 40;

    RETURN QUERY
    SELECT 
        a.id,
        a.title,
        a.source_name,
        a.source_url,
        a.category,
        a.depth_level,
        a.tldr,
        a.takeaways,
        a.code_snippet,
        a.github_repo_name,
        a.github_stars,
        a.metric_label,
        a.metric_value,
        a.published_at,
        (1 - (e.embedding <=> query_embedding))::FLOAT AS similarity
    FROM articles a
    JOIN article_embeddings e ON a.id = e.article_id
    WHERE (filter_category IS NULL OR a.category = filter_category)
      AND (1 - (e.embedding <=> query_embedding)) > match_threshold
    ORDER BY e.embedding <=> query_embedding ASC
    LIMIT match_count;
END;
$$;